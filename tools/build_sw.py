"""Write public/sw.js and public/version.mjs: the list of files to cache and a version from their contents.

Usage: python3 -I tools/build_sw.py public <game-slug>

Run after every change under public/. The version changes whenever any file changes, which is what
makes phones pick up the update.
"""

import hashlib
import os
import sys

root = sys.argv[1]
slug = sys.argv[2]
files = []
for d, _, names in os.walk(root):
    for n in sorted(names):
        if n in ("sw.js", "version.mjs", ".DS_Store"):
            continue
        files.append(os.path.relpath(os.path.join(d, n), root).replace(os.sep, "/"))
files.sort()
h = hashlib.sha1()
for f in files:
    h.update(f.encode())
    h.update(open(os.path.join(root, f), "rb").read())
version = h.hexdigest()[:10]
open(os.path.join(root, "version.mjs"), "w").write(f'export const VERSION = "{version}";\n')
urls = ["./", "version.mjs"] + files
body = f"""// Generated by tools/build_sw.py. Do not edit.
const CACHE = "{slug}-{version}";
const FILES = {urls!r};

// Fetch past the browser's HTTP cache so a new version never stores stale files.
self.addEventListener("install", (e) => {{
  e.waitUntil(
    caches.open(CACHE)
      .then((c) => Promise.all(FILES.map((u) => fetch(new Request(u, {{ cache: "reload" }})).then((r) => {{
        if (!r.ok) throw new Error(u + " " + r.status);
        return c.put(u, r);
      }}))))
      .then(() => self.skipWaiting()),
  );
}});
self.addEventListener("activate", (e) => {{
  e.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()),
  );
}});
self.addEventListener("fetch", (e) => {{
  if (e.request.method !== "GET") return;
  e.respondWith(caches.match(e.request, {{ ignoreSearch: true }}).then((hit) => hit || fetch(e.request)));
}});
""".replace("'", '"')
open(os.path.join(root, "sw.js"), "w").write(body)
print(len(urls), "files, version", version)
